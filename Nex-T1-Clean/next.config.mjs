const resolveNextServerDir = (outputPath) => {
  if (!outputPath) {
    return null;
  }

  const normalizedOutputPath = path.resolve(outputPath);
  const resolveBySegment = (distDir) => {
    const segment = path.normalize(path.join(distDir, "server"));
    const idx = normalizedOutputPath.lastIndexOf(segment);
    if (idx === -1) {
      return null;
    }
    return normalizedOutputPath.slice(0, idx + segment.length);
  };

  const activeMatch = resolveBySegment(nextDistDir);
  if (activeMatch) {
    return activeMatch;
  }

  const fallbackMatch = resolveBySegment(".next");
  if (fallbackMatch) {
    return fallbackMatch;
  }

  return null;
};

