const purgeStaleServerOutputForDev = () => {
  if (process.env.NODE_ENV === "production") {
    return;
  }

  try {
    const prodChunksDir = path.join(nextServerDir, "chunks");
    if (!fs.existsSync(prodChunksDir)) {
      return;
    }

    fs.rmSync(nextServerDir, { recursive: true, force: true });
    console.warn(`[next-config] Removed stale ${nextDistDir}/server artifacts generated by a previous production build to avoid chunk mismatches in dev.`);
  } catch (error) {
    console.warn("[next-config] Failed to purge stale dev server output", error);
  }
};

const ensureAppPathsManifestFile = (serverDir) => {
  if (!serverDir) {
    return;
  }

  fs.mkdirSync(serverDir, { recursive: true });
  const manifestTarget = path.join(serverDir, APP_PATHS_MANIFEST_NAME);
  const shouldWrite = !fs.existsSync(manifestTarget) || fs.statSync(manifestTarget).size === 0;

  if (shouldWrite) {
    fs.writeFileSync(manifestTarget, APP_PATHS_MANIFEST_STUB, "utf8");
  }
};

const bootstrapAppPathsManifest = () => {
  try {
    ensureAppPathsManifestFile(nextServerDir);
  } catch (error) {
    console.warn("[next-config] Failed to bootstrap app-paths-manifest stub", error);
  }
};

const bootstrapPagesManifest = () => {
  try {
    fs.mkdirSync(nextServerDir, { recursive: true });
    const manifestTarget = path.join(nextServerDir, PAGES_MANIFEST_NAME);
    if (!fs.existsSync(manifestTarget)) {
      fs.writeFileSync(manifestTarget, PAGES_MANIFEST_STUB, "utf8");
    }
  } catch (error) {
    console.warn("[next-config] Failed to bootstrap pages-manifest stub", error);
  }
};

