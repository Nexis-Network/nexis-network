const WEBPACK_CACHE_SEGMENTS = ["client", "server", "edge-server"];

let hasPurgedWebpackCache = false;

const cleanupWebpackCachePlugin = ({ dev }) => {
  // Avoid clearing webpack's filesystem cache mid-run in dev; Next.js's loader
  // still expects the existing pack files during hot reload which results in
  // ENOENT errors when the cache vanishes before it can be replaced. When a
  // purge is explicitly requested, we still comply and let the caller accept
  // the trade-off.
  const forcePurge = process.env.NEXT_FORCE_PURGE_WEBPACK_CACHE === "1";
  const shouldSkipPurge = dev && !forcePurge;

  if (shouldSkipPurge) {
    return { apply() { } };
  }

  const purgeCache = () => {
    if (hasPurgedWebpackCache) {
      return;
    }

    const cacheRoot = nextWebpackCacheDir;
    if (!fs.existsSync(cacheRoot)) {
      hasPurgedWebpackCache = true;
      return;
    }

    const envLabel = dev ? "development" : "production";
    const targets = forcePurge
      ? [cacheRoot]
      : WEBPACK_CACHE_SEGMENTS.map((segment) => path.join(cacheRoot, `${segment}-${envLabel}`));

    const removed = [];

    try {
      for (const target of targets) {
        if (!fs.existsSync(target)) {
          continue;
        }

        fs.rmSync(target, { recursive: true, force: true });
        removed.push(path.relative(process.cwd(), target) || `${nextDistDir}/cache/webpack`);
      }

      if (removed.length > 0) {
        const label = forcePurge ? `${nextDistDir}/cache/webpack` : removed.join(", ");
        console.warn(`[webpack] Cleared stale filesystem cache at ${label}`);
      }
    } catch (error) {
      console.warn("[webpack] Failed to purge webpack cache", error);
    } finally {
      hasPurgedWebpackCache = true;
    }
  };

  return {
    apply(compiler) {
      compiler.hooks.beforeRun.tap("CleanupWebpackCache", purgeCache);
      compiler.hooks.watchRun.tap("CleanupWebpackCache", purgeCache);
    },
  };
};

const ensurePagesManifestPlugin = () => ({
  apply(compiler) {
    const ensureDocumentStub = () => {
      try {
        const serverDir = resolveNextServerDir(compiler.options.output.path);
        if (!serverDir) {
          return;
        }

        const pagesDir = path.join(serverDir, "pages");
        fs.mkdirSync(pagesDir, { recursive: true });
        const documentTarget = path.join(pagesDir, "_document.js");
        if (!fs.existsSync(documentTarget)) {
          const source = require.resolve("next/dist/pages/_document.js");
          fs.writeFileSync(documentTarget, `module.exports = require("${source.replace(/\\/g, "\\\\")}");\n`, "utf8");
        }
      } catch (error) {
        console.warn("[bundle-analyzer] Failed to ensure _document stub", error);
      }
    };

    const mergeBuiltinsIntoManifest = () => {
      try {
        const serverDir = resolveNextServerDir(compiler.options.output.path);
        if (!serverDir) {
          return;
        }

        const pagesDir = path.join(serverDir, "pages");
        const manifestPath = path.join(serverDir, "pages-manifest.json");

        fs.mkdirSync(pagesDir, { recursive: true });

        let manifest = {};
        let updated = false;
        if (fs.existsSync(manifestPath)) {
          try {
            manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
          } catch {
            manifest = {};
            updated = true;
          }
        } else {
          updated = true;
        }

        const builtins = {
          "/_app": "pages/_app.js",
          "/_error": "pages/_error.js",
          "/_document": "pages/_document.js",
          "/_not-found": "pages/_not-found.js",
        };

        for (const [route, file] of Object.entries(builtins)) {
          if (!manifest[route]) {
            manifest[route] = file;
            updated = true;
          }

          const targetFile = path.join(pagesDir, file.replace(/^pages\//, ""));
          if (!fs.existsSync(targetFile)) {
            const importTarget =
              route === "/_not-found"
                ? "../app/_not-found/page.js"
                : require.resolve(`next/dist/pages/${file.replace(/^pages\//, "")}`);
            fs.writeFileSync(targetFile, `module.exports = require("${importTarget.replace(/\\/g, "\\\\")}");\n`, "utf8");
          }
        }

        if (updated) {
          fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2), "utf8");
        }
      } catch (error) {
        console.warn("[bundle-analyzer] Failed to ensure pages-manifest.json", error);
      }
    };

    compiler.hooks.emit.tap("EnsurePagesManifest", () => {
      ensureDocumentStub();
      mergeBuiltinsIntoManifest();
    });
    compiler.hooks.afterEmit.tap("EnsurePagesManifest", mergeBuiltinsIntoManifest);
    compiler.hooks.beforeCompile.tap("EnsurePagesManifest", () => {
      ensureDocumentStub();
      mergeBuiltinsIntoManifest();
    });
  },
});

