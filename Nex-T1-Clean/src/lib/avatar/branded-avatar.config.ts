function parseOverlaySegments(pathData: string): ReadonlyArray<OverlaySegment> {
  return Object.freeze(
    [...pathData.matchAll(/M(\d+) (\d+)H(\d+)/g)].map((match) => {
      const [, x1 = "0", y = "0", x2 = "1"] = match;

      return Object.freeze({
        x1: Number.parseInt(x1, 10),
        y: Number.parseInt(y, 10),
        x2: Number.parseInt(x2, 10),
        strokeWidth: AVATAR_V1_BASE_STROKE_WIDTH,
      });
    }),
  );
}

