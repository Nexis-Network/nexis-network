function mergeTrees(base: TranslationTree, extension: TranslationTree): TranslationTree {
  const result: TranslationTree = { ...base };

  for (const [key, value] of Object.entries(extension)) {
    const existing = result[key];

    if (
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      existing &&
      typeof existing === "object" &&
      !Array.isArray(existing)
    ) {
      result[key] = mergeTrees(existing, value);
      continue;
    }

    result[key] = value;
  }

  return result;
}

