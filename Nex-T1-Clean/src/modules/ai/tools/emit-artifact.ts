const ARTIFACT_PATCH_SCHEMA: JSONSchema7 = {
  type: "object",
  description:
    "Incremental artifact patch operation. Use these with `base` for large object- or array-heavy artifacts.",
  properties: {
    op: enumProp(
      "Patch operation.",
      ["set", "merge", "append", "upsertByKey", "removeByKey"],
    ),
    path: stringProp("JSON pointer path inside the artifact payload."),
    key: stringProp("Stable object key for keyed array mutations."),
    value: {
      description: "JSON value used by the patch operation.",
    },
  },
  required: ["op", "path"],
  additionalProperties: false,
};

function isRecord(value: unknown): value is Record<string, UntypedJson> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function materializeArtifactPayload(input: Record<string, unknown>) {
  if (isRecord(input.payload)) {
    return input.payload;
  }

  const base = isRecord(input.base) ? input.base : {};
  const patches = normalizeArtifactPatchOperations(input.patches);

  if (isRecord(input.base) || patches.length > 0) {
    const materialized = applyArtifactPatches(base, patches);
    return isRecord(materialized) ? materialized : {};
  }

  if (typeof input.content === "string") {
    return { text: input.content };
  }

  return {};
}

const emitArtifactSchema = createToolSchema(
  {
    artifactType: enumProp(
      "Artifact type to render in the artifact panel.",
      EMIT_ARTIFACT_TYPES,
    ),
    identifier: stringProp(
      "Stable artifact identifier (optional, autogenerated when omitted).",
      { minLength: 1, maxLength: 120 },
    ),
    title: stringProp("User-visible artifact title.", { minLength: 1, maxLength: 160 }),
    payload: objectProp(
      "Artifact payload object. Keep this as valid JSON object data.",
      {},
    ),
    base: objectProp(
      "Optional base artifact payload object. Prefer this plus `patches` when streaming large structured artifacts.",
      {},
    ),
    patches: arrayProp(
      "Optional incremental patch operations applied on top of `base`.",
      ARTIFACT_PATCH_SCHEMA,
    ),
    content: stringProp(
      "Optional raw text content (for markdown/text artifacts). Prefer payload for structured data.",
    ),
  },
  ["artifactType"],
  { additionalProperties: false },
);

export const emitArtifactTool = createTool({
  description:
    "Emit a structured UI artifact. Use `payload` for complete artifacts, or `base` plus `patches` for large streaming artifacts. Do not write raw JSON or <antArtifact> blocks in assistant text.",
  schema: emitArtifactSchema,
  execute: async (input) => {
    const now = Date.now();
    const artifactType = String(input.artifactType ?? "file-analysis").trim();
    const identifierRaw = typeof input.identifier === "string" ? input.identifier.trim() : "";
    const titleRaw = typeof input.title === "string" ? input.title.trim() : "";
    const payload = materializeArtifactPayload(input);
    const identifier = identifierRaw || `artifact_${now.toString(16)}`;
    const title = titleRaw || "Generated Artifact";
    const artifactEnvelope = {
      id: identifier,
      type: artifactType,
      title,
      status: "complete" as const,
      version: 1,
      createdAt: now,
      updatedAt: now,
      payload,
    };

    return {
      artifactType,
      identifier,
      title,
      payload,
      artifact: {
        type: artifactType,
        identifier,
        title,
        payload,
      },
      parts: [
        {
          type: `data-artifact-${artifactType}`,
          data: artifactEnvelope,
        },
      ],
      status: "ok",
    };
  },
});
