"use client";

import Link from "next/link";
import { ArrowUpRight, FolderCode, Search } from "lucide-react";
import { useMemo, useState } from "react";

import {
  SettingsPage,
  SettingsPageHeader,
  SettingsSection,
} from "@/components/settings-v2/primitives/page";
import { Badge } from "@/components/ui/badge";
import { Input } from "@/components/ui/input";
import { Skeleton } from "@/components/ui/skeleton";
import { useProfileAggregate } from "@/hooks/user/use-profile-aggregate";

function formatDate(value: string) {
  const dt = new Date(value);
  if (Number.isNaN(dt.getTime())) return "Unknown";
  return dt.toLocaleString();
}

export default function SettingsArtifactsPage() {
  const { data, isLoading } = useProfileAggregate();
  const [query, setQuery] = useState("");

  const artifacts = useMemo(() => {
    const list = Array.isArray(data?.artifacts) ? data.artifacts : [];
    const normalizedQuery = query.trim().toLowerCase();
    if (!normalizedQuery) return list;

    return list.filter((artifact) => {
      const tags = Array.isArray(artifact.tags) ? artifact.tags : [];
      const haystack = [
        artifact.artifactId,
        artifact.artifactType,
        artifact.title ?? "",
        ...tags,
      ]
        .join(" ")
        .toLowerCase();
      return haystack.includes(normalizedQuery);
    });
  }, [data?.artifacts, query]);

  return (
    <SettingsPage>
      <SettingsPageHeader
        title="Artifacts"
        description="Review code sandboxes, previews, and analysis artifacts generated by your sessions."
        badge={<FolderCode className="h-5 w-5 text-[var(--settings-foreground-subtle)]" />}
      />

      <SettingsSection
        title="Search artifacts"
        description="Filter by type, title, tag, or artifact ID."
        className="max-w-[720px]"
      >
        <div className="relative">
          <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-[var(--settings-foreground-muted)]" />
          <Input
            value={query}
            onChange={(event) => setQuery(event.target.value)}
            placeholder="Search by type, title, tag, or artifact ID"
            className="pl-9"
          />
        </div>
      </SettingsSection>

      <SettingsSection
        tone="ledger"
        title="Recent artifacts"
        badge={
          <Badge
            variant="outline"
            className="border-[var(--settings-border-soft)] bg-white/[0.03] text-[var(--settings-foreground-muted)]"
          >
            {data?.usage?.artifactsLast30d ?? 0} in last 30 days
          </Badge>
        }
      >
        {isLoading ? (
          <div className="space-y-2 px-5 py-5">
            {Array.from({ length: 6 }).map((_, index) => (
              <Skeleton key={index} className="h-14 w-full bg-white/5" />
            ))}
          </div>
        ) : artifacts.length === 0 ? (
          <div className="px-5 py-12 text-sm text-[var(--settings-foreground-muted)]">
            No artifacts found for this user yet.
          </div>
        ) : (
          <div data-settings-row-list>
            {artifacts.map((artifact) => (
              <div
                key={artifact.artifactId}
                className="flex items-start justify-between gap-4 px-5 py-4"
              >
                <div className="space-y-1">
                  <p className="text-sm font-medium text-[var(--settings-foreground-strong)]">
                    {artifact.title ?? artifact.artifactId}
                  </p>
                  <div className="flex flex-wrap items-center gap-2 text-xs text-[var(--settings-foreground-muted)]">
                    <Badge
                      variant="outline"
                      className="border-[var(--settings-border-soft)] bg-white/[0.03] uppercase text-[var(--settings-foreground-muted)]"
                    >
                      {artifact.artifactType}
                    </Badge>
                    <span>{formatDate(artifact.createdAt)}</span>
                    {(Array.isArray(artifact.tags) ? artifact.tags : []).slice(0, 4).map((tag) => (
                      <Badge
                        key={`${artifact.artifactId}-${tag}`}
                        variant="outline"
                        className="border-[var(--settings-border-soft)] bg-transparent text-[var(--settings-foreground-subtle)]"
                      >
                        #{tag}
                      </Badge>
                    ))}
                  </div>
                </div>

                <Link
                  href={`/artifacts/${encodeURIComponent(artifact.artifactId)}`}
                  className="inline-flex items-center gap-1 rounded-[10px] border border-[var(--settings-border-soft)] bg-[var(--settings-surface)] px-3 py-2 text-xs text-[var(--settings-foreground-muted)] transition-colors hover:bg-[var(--settings-elevated)] hover:text-[var(--settings-foreground-strong)]"
                >
                  Open
                  <ArrowUpRight className="h-3.5 w-3.5" />
                </Link>
              </div>
            ))}
          </div>
        )}
      </SettingsSection>
    </SettingsPage>
  );
}
