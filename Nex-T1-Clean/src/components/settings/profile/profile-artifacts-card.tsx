"use client";

import { ArrowUpRight } from "lucide-react";
import { FileIcon } from "@/components/sidebar-03/animated-icons";
import Link from "next/link";

import { BentoCard } from "@/components/settings/shared/bento-card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/settings/shared/settings-button";
import { Skeleton } from "@/components/ui/skeleton";
import type { ArtifactSummary } from "@/lib/user/profile";

type ProfileArtifactsCardProps = {
  artifacts?: ArtifactSummary[];
  isLoading: boolean;
};

export function ProfileArtifactsCard({ artifacts, isLoading }: ProfileArtifactsCardProps) {
  if (isLoading) {
    return (
      <BentoCard>
        <div className="space-y-1">
          <Skeleton className="h-5 w-36 bg-white/5" />
          <Skeleton className="h-4 w-56 bg-white/5" />
        </div>
        <div className="mt-4 space-y-2">
          {Array.from({ length: 3 }).map((_, index) => (
            <Skeleton key={index} className="h-16 w-full rounded-lg bg-white/5" />
          ))}
        </div>
      </BentoCard>
    );
  }

  const list = (artifacts ?? []).slice(0, 4);

  return (
    <BentoCard>
      <div className="flex items-center justify-between gap-3">
        <div className="space-y-1">
          <h3 className="text-sm font-medium text-[var(--bento-text-primary)]">Recent Artifacts</h3>
          <p className="text-xs text-[var(--bento-text-muted)]">
            Work generated by your agents in the last 30 days.
          </p>
        </div>
        <Badge variant="outline">
          <FileIcon className="h-3.5 w-3.5" />
          {list.length}
        </Badge>
      </div>

      <div className="mt-4 space-y-2">
        {list.length === 0 ? (
          <div className="rounded-lg border border-[var(--bento-border)] bg-white/[0.03] p-4 text-sm text-[var(--bento-text-muted)]">
            No artifacts yet. Create your first workflow or run an agent to generate output.
          </div>
        ) : (
          list.map((artifact) => (
            <div
              key={artifact.artifactId}
              className="flex items-start justify-between gap-3 rounded-lg border border-[var(--bento-border)] bg-white/[0.03] p-3"
            >
              <div className="space-y-1">
                <p className="text-sm font-regular text-[var(--bento-text-primary)]">
                  {artifact.title ?? artifact.artifactId}
                </p>
                <div className="flex flex-wrap items-center gap-2 text-xs text-[var(--bento-text-muted)]">
                  <Badge variant="outline" className="uppercase">
                    {artifact.artifactType}
                  </Badge>
                  <span>{formatDateTime(artifact.createdAt)}</span>
                  {artifact.tags?.slice(0, 3).map((tag) => (
                    <Badge key={tag} variant="outline">
                      #{tag}
                    </Badge>
                  ))}
                </div>
              </div>
              <Button variant="ghost" size="sm" asChild>
                <Link href={`/artifacts/${encodeURIComponent(artifact.artifactId)}`}>
                  Open
                  <ArrowUpRight className="ml-1 h-4 w-4" />
                </Link>
              </Button>
            </div>
          ))
        )}
      </div>
    </BentoCard>
  );
}

function formatDateTime(value: string) {
  const dt = new Date(value);
  if (Number.isNaN(dt.getTime())) return "\u2014";
  return dt.toLocaleString();
}
