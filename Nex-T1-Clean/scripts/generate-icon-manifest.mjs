#!/usr/bin/env node

/**
 * Generates a manifest of available icon assets so the frontend can avoid
 * requesting non-existent files (which causes noisy 404 logs).
 */

import { promises as fs } from "fs";
import path from "path";

const PROJECT_ROOT = process.cwd();
const ICON_ROOT = path.join(PROJECT_ROOT, "public", "icons");
const COLLECTIONS = ["chain-icons", "web3-icons", "wallet-icons"];
const TARGET_FILE = path.join(PROJECT_ROOT, "lib", "generated", "icon-manifest.ts");

const normalizeTokenSlug = (value) => {
  if (!value) return "";
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");
};

const ensureDir = async (dir) => {
  try {
    await fs.mkdir(dir, { recursive: true });
  } catch {
    // directory already exists
  }
};

const encodeFileName = (fileName) =>
  fileName
    .split("/")
    .map((segment) => encodeURIComponent(segment))
    .join("/");

const gatherManifest = async () => {
  const manifest = Object.fromEntries(COLLECTIONS.map((collection) => [collection, {}]));

  for (const collection of COLLECTIONS) {
    const collectionDir = path.join(ICON_ROOT, collection);

    let entries = [];
    try {
      entries = await fs.readdir(collectionDir, { withFileTypes: true });
    } catch (error) {
      if (error && error.code === "ENOENT") {
        continue;
      }
      throw error;
    }

    const collectionManifest = manifest[collection];

    for (const entry of entries) {
      if (!entry.isFile()) {
        continue;
      }

      if (!entry.name.toLowerCase().endsWith(".svg")) {
        continue;
      }

      const baseName = entry.name.replace(/\.svg$/i, "");
      const slug = normalizeTokenSlug(baseName);
      if (!slug) {
        continue;
      }

      const encodedFileName = encodeFileName(entry.name);
      const relativePath = `/icons/${collection}/${encodedFileName}`;

      if (!collectionManifest[slug]) {
        collectionManifest[slug] = [];
      }

      if (!collectionManifest[slug].includes(relativePath)) {
        collectionManifest[slug].push(relativePath);
      }
    }

    for (const slug of Object.keys(collectionManifest)) {
      collectionManifest[slug].sort((a, b) => a.localeCompare(b));
    }
  }

  return manifest;
};

const buildFileContents = (manifest) => {
  const header = `/* eslint-disable */\n// This file is auto-generated by scripts/generate-icon-manifest.mjs.\n// Do not edit manually.\n\n`;
  const collectionsType = `export type IconCollection = ${COLLECTIONS.map((collection) => `"${collection}"`).join(" | ")};\n\n`;
  const manifestString = JSON.stringify(manifest, null, 2);
  const exportStatement = `export const ICON_MANIFEST: Record<IconCollection, Record<string, readonly string[]>> = ${manifestString};\n`;

  return header + collectionsType + exportStatement;
};

const main = async () => {
  await ensureDir(path.dirname(TARGET_FILE));
  const manifest = await gatherManifest();
  const fileContents = buildFileContents(manifest);
  await fs.writeFile(TARGET_FILE, `${fileContents}`, "utf8");
};

main().catch((error) => {
  console.error("Failed to generate icon manifest:");
  console.error(error);
  process.exit(1);
});
